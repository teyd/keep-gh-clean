import { defineConfig, type Plugin, lazyPlugins } from 'vite-plus'
import react from '@vitejs/plugin-react'
import tailwindcss from '@tailwindcss/vite'
import { varlockVitePlugin } from '@varlock/vite-integration'
import { ENV } from 'varlock/env'

// The token never leaves the browser except to api.github.com. Only applied to
// production builds because the dev server needs inline scripts and websockets.
const CSP = [
  "default-src 'self'",
  'connect-src https://api.github.com',
  "img-src 'self' data: https://avatars.githubusercontent.com",
  "style-src 'self' 'unsafe-inline'",
  "script-src 'self'",
  "base-uri 'none'",
  "form-action 'none'",
].join('; ')

function csp(): Plugin {
  return {
    name: 'csp',
    apply: 'build',
    transformIndexHtml: () => [
      {
        tag: 'meta',
        attrs: { 'http-equiv': 'Content-Security-Policy', content: CSP },
        injectTo: 'head-prepend',
      },
    ],
  }
}

export default defineConfig({
  fmt: {
    singleQuote: true,
    semi: false,
    printWidth: 100,
    // Generated by varlock from .env.schema.
    ignorePatterns: ['src/env.d.ts'],
  },
  lint: {
    ignorePatterns: ['src/env.d.ts'],
    jsPlugins: [{ name: 'vite-plus', specifier: 'vite-plus/oxlint-plugin' }],
    rules: { 'vite-plus/prefer-vite-plus-imports': 'error' },
    options: { typeAware: true, typeCheck: true },
  },
  base: ENV.BASE_PATH,
  plugins: lazyPlugins(() => [varlockVitePlugin(), react(), tailwindcss(), csp()]),
})
